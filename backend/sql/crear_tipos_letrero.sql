-- Catálogo de tipos de letrero.
-- Coincide con el modelo Django TipoLetrero (db_table = tipos_letrero).

CREATE TABLE IF NOT EXISTS tipos_letrero (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo      varchar(20)  NOT NULL,
    nombre      varchar(100) NOT NULL,
    esta_activo boolean      NOT NULL DEFAULT true,
    CONSTRAINT tipos_letrero_codigo_key UNIQUE (codigo)
);
